"""구어체 → 법률용어 정적 사전 (colloquial-legal-mapping G1b).

의도분석(analyze_intent)이 실패한 폴백에서만 쓴다 — 정상 경로의 변환은
LLM(프롬프트 지시, 실측 8/8 정확)이 담당하고, 이 사전은 LLM 없이 동작하는
최후 방어선이다. 구어 원문만으로는 판례·행정해석·해설서 검색 도달이 0/8
(2026-08-20 실측)이라, 여기서 뽑은 법률용어를 검색 쿼리에 병기해 법률
코퍼스 도달을 살린다.

수록 기준 — **활용형이 명확한 고신뢰 패턴만**:
미변환의 비용은 Q&A 도달로의 강등이지만(구어-구어 매칭은 사전 없이도 된다),
오변환의 비용은 무관한 판례가 답변 근거로 실리는 것이다. 비용이 비대칭이므로
애매한 표현(예: "관두다" — 자진사직/권고사직 중의적)은 넣지 않는다.
해설서 헤딩 위생의 "오폐기 < 오복원"과 같은 방향의 원칙이다.

from __future__ import annotations 규약은 app/core/* 공통.
"""
from __future__ import annotations

import re
import unicodedata

# (패턴, 법률용어들, 억제자). 패턴은 원문에 대해 re.search로 평가하고,
# 억제자(suppressor)가 함께 매칭되면 그 항목은 무효다 — 노동상담 언어는
# 구어와 무관 문맥이 어휘를 공유하므로("기계에 손이 잘렸다"는 산재지 해고가
# 아니다) 양성 패턴만으로는 좁힐 수 없다. abuse_guard의 _BENIGN_ACTOR와
# 같은 설계다. 근접 제한({0,N})을 두는 이유: "까"·"다쳤" 같은 짧은 어간은
# 단독으로 두면 무관 문장에 오매칭한다.
_ENTRY = tuple[re.Pattern[str], tuple[str, ...], re.Pattern[str] | None]

# 해고 계열 공통 억제자 — 이동 지시("출장 나가라")는 해고 통보가 아니다.
_MOVE_CONTEXT = re.compile(r"출장|외근|현장|파견")
# 신체 절단 문맥 — "잘렸다"가 해고가 아니라 산재(부상)인 경우.
_BODY_CONTEXT = re.compile(r"손가락|손목|발가락|손|팔|다리|발|기계|절단|베")

COLLOQUIAL_LEGAL_MAP: tuple[_ENTRY, ...] = (
    # ── 해고 ──────────────────────────────────────────────────────────────
    # "잘렸다/짤렸다"는 노동 상담에서 해고의 압도적 다수 표현(실측 c1·c5).
    (re.compile(r"잘렸|짤렸|잘린다|짤린다|잘릴|짤릴"),
     ("부당해고", "해고예고수당"), _BODY_CONTEXT),
    # "나가라(고/네/는)"·"나오지 말라" — 구두 해고 통보(실측 c2·c6).
    (re.compile(r"나오지\s*말|나가라(?:고|네|는|니)|그만\s*나오"),
     ("부당해고", "해고 통보"), _MOVE_CONTEXT),
    # 당일·즉시 통보 — 해고예고(근기법 제26조) 쟁점.
    (re.compile(r"오늘\s*부로|당일\s*해고"),
     ("해고예고수당", "해고예고"), None),
    # 사직서 강요 — 사직 의사표시의 하자, 실질 해고(실측 c7).
    (re.compile(r"사직서.{0,10}(쓰라|쓰래|강요|눈치)"),
     ("사직 강요", "권고사직"), None),
    # "구조조정"은 일상어지만 법률 쟁점은 경영상 해고(근기법 제24조).
    (re.compile(r"구조\s*조정"),
     ("경영상 해고", "정리해고"), None),
    # 임신·출산 문맥의 해고 — 절대 금지 사유(근기법 제23조제2항).
    # 이동 지시("임신 중인데 외근 나가라")는 배치 쟁점이지 해고가 아니다.
    (re.compile(r"임신.{0,10}(잘렸|짤렸|나가|해고)"),
     ("임산부 해고 금지",), _MOVE_CONTEXT),

    # ── 임금 ──────────────────────────────────────────────────────────────
    # "퉁치다" — 상계 합의 제안. 임금 전액불 원칙(근기법 제43조) 쟁점(실측 c3).
    (re.compile(r"퉁치|퉁쳐"),
     ("임금 상계 금지", "임금 전액 지급 원칙"), None),
    # "월급에서 깐다" — 일방 공제. 활용형을 명시해 '까먹다' 류 오매칭을 막는다.
    (re.compile(r"(월급|임금|급여)(?:에서)?.{0,4}(까겠|깐다|깐대|까고)"),
     ("임금 공제", "임금 전액 지급 원칙"), None),
    # "월급을 깎는다" — 일방 삭감. 공제와 쟁점이 다르다(불이익 변경).
    # {0,8}: "일방적으로" 같은 부사 삽입을 허용하되 문장 경계는 넘지 않는다.
    (re.compile(r"(월급|임금|급여).{0,8}깎"),
     ("임금 삭감", "취업규칙 불이익 변경"), None),
    # 미지급 일반 — "안 줘요/못 받았/떼였/밀렸"(실측 c5). '급여'는 고정폭
    # lookbehind로 실업·구직·휴직·요양급여(고용보험/산재 쟁점)를 제외한다 —
    # 억제자 방식을 쓰면 "실업급여도 월급도 못 받았다" 복합 질의에서 임금체불
    # 매핑까지 죽는다.
    (re.compile(r"(돈|월급|임금|(?<!실업)(?<!구직)(?<!휴직)(?<!요양)급여|수당|퇴직금)"
                r".{0,10}(안\s*줘|안\s*주|못\s*받|떼먹|떼였|밀렸|밀리)"),
     ("임금체불",), None),
    # 현물 대체 지급 — 통화불 원칙(근기법 제43조제1항)(실측 c8).
    (re.compile(r"(밥값|식대|현물|상품권).{0,8}(때우|때운|대신|대체)"),
     ("임금 통화 지급 원칙", "수당 대체 지급"), None),

    # ── 직장 내 괴롭힘 ────────────────────────────────────────────────────
    # "갈구다"·"갑질"·"왕따" — 괴롭힘 상담의 관용 표현이고 다른 법률 쟁점과
    # 어휘를 공유하지 않아 단독으로도 고신뢰.
    (re.compile(r"갈구|갈궈|갈굼"), ("직장 내 괴롭힘",), None),
    (re.compile(r"갑질"), ("직장 내 괴롭힘",), None),
    (re.compile(r"따돌리|따돌림|왕따"), ("직장 내 괴롭힘", "집단 따돌림"), None),

    # ── 산재 ──────────────────────────────────────────────────────────────
    # "공상 처리" — 산재 미신고 합의 관행. '공상(空想)' 오매칭을 막기 위해
    # '처리'와 결합할 때만 잡는다.
    (re.compile(r"공상\s*처리"), ("산재보상", "공상 처리 합의"), None),
    # 근무 문맥의 부상 — 업무상 재해. '다쳤' 단독은 사적 부상과 구분 불가라
    # 근무 문맥어와 근접할 때만.
    (re.compile(r"(일하다|일하는\s*중|작업\s*중|근무\s*중|회사에서).{0,6}다(쳤|쳐|침)"),
     ("산재보상", "업무상 재해", "요양급여"), None),

    # ── 4대보험·근로자성 ──────────────────────────────────────────────────
    # "안 들다"는 미가입("안 들어줬다")과 미입금("안 들어왔다")이 갈린다 —
    # 입금 문맥은 억제해 미가입 쟁점만 남긴다.
    (re.compile(r"(보험|연금).{0,8}(안\s*들|미가입|안\s*가입|가입\s*안)"),
     ("4대보험 가입의무",), re.compile(r"들어오|들어왔|입금|보험금")),
    # "3.3%"(사업소득 원천징수) — 위장 프리랜서/근로자성의 관용 신호.
    (re.compile(r"삼쩜삼|3\.3\s*(%|퍼|프로)"),
     ("근로자성 인정", "프리랜서 계약"), None),

    # ── 근로계약·기타 ─────────────────────────────────────────────────────
    # 계약서 미작성/미교부 — 근기법 제17조 명시·교부 의무의 관용 표현.
    (re.compile(r"계약서.{0,8}(안\s*썼|안\s*쓰|못\s*받|없)"),
     ("근로계약서 미작성", "근로조건 명시 의무"), None),
    # "쪼개기 계약" — 기간제 반복 갱신. 관용어로 굳어져 고신뢰.
    (re.compile(r"쪼개기\s*계약"),
     ("기간제 쪼개기 계약", "갱신기대권"), None),
    # 취업방해 — 블랙리스트(근기법 제40조). 다의성 없는 외래어라 단독 고신뢰.
    (re.compile(r"블랙\s*리스트"),
     ("취업방해 금지",), None),
    # 연차 사용 방해 — "못 쓰게/반려"(연차는 법률용어지만 쟁점어를 병기).
    (re.compile(r"연차.{0,8}(못\s*쓰|안\s*줘|반려|눈치)"),
     ("연차휴가 사용권", "연차수당"), None),
)


def map_colloquial_terms(text: str, max_terms: int = 6) -> list[str]:
    """text에 매칭된 법률용어(등장 순서 유지, 중복 제거, 최대 max_terms).

    매칭이 없으면 빈 리스트 — 호출부는 그대로 기존 폴백(원문 검색)을 탄다.
    NFC 정규화를 여기서 거는 이유: 웹 3경로는 abuse_guard가 정규화해 주지만
    guard_ctx=None 호출부(CLI·벤치마크·fixture)는 거치지 않는다 — NFD 입력이면
    [가-힣] 문자 클래스가 조용히 0매칭한다(NFD로 벡터 474개를 잃은 전력).

    max_terms 기본 6 중 검색 rule 쿼리에는 상위 4개만 실린다
    (build_precedent_queries가 [:4]) — 5·6번째는 NLRC 판정사례 검색과
    GraphRAG 시드로만 쓰인다. 의도된 배분이다.
    """
    text = unicodedata.normalize("NFC", text)
    terms: list[str] = []
    seen: set[str] = set()
    for pattern, mapped, suppressor in COLLOQUIAL_LEGAL_MAP:
        if len(terms) >= max_terms:
            break
        if not pattern.search(text):
            continue
        if suppressor is not None and suppressor.search(text):
            continue
        for term in mapped:
            if term not in seen:
                seen.add(term)
                terms.append(term)
                if len(terms) >= max_terms:
                    break
    return terms
